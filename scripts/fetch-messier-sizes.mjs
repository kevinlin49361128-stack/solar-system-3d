#!/usr/bin/env node
/**
 * One-shot helper to enrich `src/data/messier.ts` with apparent
 * angular sizes (major × minor axis, arcmin) for all 110 Messier
 * objects.
 *
 * Data source: NASA / SEDS Messier catalogue
 *   https://www.messier.seds.org/dataM.html  (HTML table)
 * mirrored into the OpenNGC v2 GitHub release for machine reading
 *   https://github.com/mattiaverga/OpenNGC/raw/master/database_files/NGC.csv
 *
 * We prefer OpenNGC because it's CSV (no HTML parsing) and includes
 * MajAx / MinAx columns in arcmin for every M-numbered object.
 *
 * Usage:
 *   node scripts/fetch-messier-sizes.mjs
 * Output:
 *   prints a Record<string, [major, minor]> literal you can paste
 *   into src/data/messier.ts as a constant lookup.
 *
 * Run once when bringing the column online; subsequent updates are
 * rare (Messier set is stable since 1781) so we don't make it a
 * recurring build step.
 */

const URL = 'https://raw.githubusercontent.com/mattiaverga/OpenNGC/master/database_files/NGC.csv';

const r = await fetch(URL);
if (!r.ok) {
  console.error(`Fetch failed: ${r.status}`);
  process.exit(1);
}
const csv = await r.text();
const lines = csv.split('\n');
const header = lines[0].split(';');
const idxName = header.indexOf('Name');
const idxM    = header.indexOf('M');
const idxMaj  = header.indexOf('MajAx');
const idxMin  = header.indexOf('MinAx');
if (idxName < 0 || idxM < 0 || idxMaj < 0 || idxMin < 0) {
  console.error('Header columns missing:', header);
  process.exit(1);
}

const sizes = {};
for (let i = 1; i < lines.length; i++) {
  const cols = lines[i].split(';');
  const mNum = cols[idxM]?.trim();
  if (!mNum) continue;
  const major = parseFloat(cols[idxMaj]);
  const minor = parseFloat(cols[idxMin]);
  if (!Number.isFinite(major)) continue;
  const id = `M${mNum.replace(/^0+/, '')}`;  // M001 → M1
  // Some Messier objects map to multiple NGC entries — take the first.
  if (sizes[id]) continue;
  sizes[id] = [
    +major.toFixed(2),
    Number.isFinite(minor) ? +minor.toFixed(2) : +major.toFixed(2),
  ];
}

const ordered = Object.keys(sizes)
  .sort((a, b) => parseInt(a.slice(1)) - parseInt(b.slice(1)));

console.log('// Auto-generated by scripts/fetch-messier-sizes.mjs from OpenNGC v2');
console.log('// Apparent angular dimensions in arcminutes, [major, minor].');
console.log('export const MESSIER_ANG_SIZES: Record<string, [number, number]> = {');
for (const id of ordered) {
  const [maj, min] = sizes[id];
  console.log(`  '${id}': [${maj}, ${min}],`);
}
console.log('};');
console.error(`\nGenerated ${ordered.length} entries.`);
